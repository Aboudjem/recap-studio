#!/usr/bin/env node
/**
 * gen-mcp-docs: write docs/mcp-tools.md from the tool list the bundled server
 * reports over stdio, so the reference cannot drift from the code.
 *
 *   node scripts/gen-mcp-docs.mjs          rewrite docs/mcp-tools.md
 *   node scripts/gen-mcp-docs.mjs --check  exit 1 when the file is stale
 */
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const out = resolve(root, "docs/mcp-tools.md");

const r = spawnSync("node", [resolve(root, "bin/recap.mjs"), "mcp"], {
  input: '{"jsonrpc":"2.0","id":1,"method":"tools/list"}\n',
  encoding: "utf8",
});
const tools = JSON.parse(r.stdout.trim().split("\n")[0]).result.tools;

const SIDE_EFFECTS = {
  create_run_artifact: "Writes one file under `artifacts/` in the working directory.",
  read_run_artifact: "None. Reads one file under `artifacts/`.",
  cache_source: "Appends one line to `.recap-studio/cache/sources.jsonl`.",
  generate_mermaid_diagram: "None.",
  render_page_screenshot: "None. Always answers `skipped`: no browser ships with the server.",
  run_accessibility_scan: "None. Always answers `skipped`: no scanner ships with the server.",
  run_lighthouse_summary: "None. Always answers `skipped`: Lighthouse does not ship with the server.",
  deploy_vercel_preview: "None. Stub: it never deploys. With `confirmed: true` and `VERCEL_TOKEN` it returns `bash scripts/deploy-preview.sh`, a script in a recap-studio checkout, to run yourself.",
  send_email_draft: "None. Stub: it never sends. It returns the draft and says to paste it into your mail client. Recap Studio ships no send code.",
  validate_content: "None. Reads the content JSON.",
  render_recap_html: "Writes `artifacts/<slug>/recap-<slug>.html`.",
};

const cell = (s) => String(s).replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();

const lines = [
  "# MCP tools",
  "",
  "<!-- Generated by scripts/gen-mcp-docs.mjs from the server's own tools/list. Do not edit by hand. -->",
  "",
  `The Recap Studio MCP server exposes ${tools.length} tools over stdio. Start it with \`node bin/recap.mjs mcp\`.`,
  "",
  "No tool makes a network call. Three tools write files, all inside the working directory.",
  "",
  "Five tools are stubs: the screenshot, accessibility and Lighthouse tools answer `skipped`, the deploy tool returns a command to run yourself, and the email tool returns a draft. None of them deploys or sends.",
  "",
  "| Tool | Arguments | What it does | Side effect |",
  "| --- | --- | --- | --- |",
  ...tools.map((t) => {
    const props = Object.keys(t.inputSchema?.properties ?? {});
    const req = new Set(t.inputSchema?.required ?? []);
    const args = props.map((p) => (req.has(p) ? `\`${p}\`` : `\`${p}\` (optional)`)).join(", ") || "none";
    return `| \`${t.name}\` | ${args} | ${cell(t.description)} | ${cell(SIDE_EFFECTS[t.name] ?? "Not documented.")} |`;
  }),
  "",
  "## Where does the server look for content?",
  "",
  "`validate_content` and `render_recap_html` take a `slug`. The first file that exists wins:",
  "",
  "1. the optional `path` argument",
  "2. `artifacts/<slug>/content.json`",
  "3. `apps/recap-web/src/content/<slug>.json` (a checkout of this repo)",
  "4. `fixtures/topics/<slug>.json` (a checkout of this repo)",
  "",
  "Save content with `create_run_artifact` as `content.json`, then validate and render it by slug.",
  "",
  "A slug or filename that resolves outside `artifacts/` is refused.",
  "",
];
const text = lines.join("\n");

if (process.argv.includes("--check")) {
  if (!existsSync(out) || readFileSync(out, "utf8") !== text) {
    console.error("docs/mcp-tools.md is stale. Run `node scripts/gen-mcp-docs.mjs` and commit the result.");
    process.exit(1);
  }
  console.log("ok: docs/mcp-tools.md matches the server");
} else {
  writeFileSync(out, text, "utf8");
  console.log(`wrote docs/mcp-tools.md (${tools.length} tools)`);
}
